class GeminiTransformService:
    """
    Isolated Gemini REST client & prompt orchestrator for Hotkey Transformations
    and the 16 Profile Command Categories.
    """

    CONNECT_TIMEOUT: float = 2.0
    READ_TIMEOUT: float = 35.0

    _groq_invalid_keys: set = set()
    _gemini_invalid_keys: set = set()

    @classmethod
    def invalidate_auth_cache(cls):
        """Clears cached rejected/invalid keys when user updates credentials in Settings."""
        cls._groq_invalid_keys.clear()
        cls._gemini_invalid_keys.clear()

    def __init__(
        self,
        config_manager: Any = None,
        api_key: str = "",
        session: Optional[requests.Session] = None,
    ):
        self.config_manager = config_manager
        self._explicit_api_key = (api_key or "").strip()
        self.session = session or requests.Session()
        self.last_model_used: str = ""
        self.last_error: str = ""
        self._cached_working_model: str = ""
        self._unavailable_models: set = set()
        self._daily_exhausted_models: set = set()

    def set_api_key(self, api_key: str) -> None:
        self._explicit_api_key = (api_key or "").strip()

    def get_api_key(self, override_key: str = "") -> str:
        """Resolves the persisted Gemini API key safely (override -> explicit -> ConfigManager -> env)."""
        candidates = [
            override_key,
            self._explicit_api_key,
        ]
        if self.config_manager is not None:
            try:
                candidates.append(self.config_manager.get_api_key())
            except Exception as e:
                logger.debug(f"ConfigManager get_api_key lookup error: {e}")
        candidates.append(os.environ.get("GEMINI_API_KEY", ""))
        candidates.append(os.environ.get("GOOGLE_API_KEY", ""))

        try:
            from app.config import sanitize_api_key
        except Exception:
            sanitize_api_key = lambda k: str(k or "").strip()

        for cand in candidates:
            cleaned = sanitize_api_key(cand)
            if cleaned and not any(bad in cleaned for bad in ("KLd4Prd", "ISb0Ozd", "KKjYK0n", "mock_working_key")):
                return cleaned
        return ""

    def _get_model_chain(self) -> List[str]:
        preferred = ""
        if self.config_manager is not None:
            try:
                preferred = str(self.config_manager.get("gemini_transform_model", "") or "").strip()
            except Exception:
                preferred = ""
        skip = self._unavailable_models | self._daily_exhausted_models
        chain: List[str] = []
        if (
            self._cached_working_model
            and self._cached_working_model.startswith(("gemini-", "gemma-"))
            and self._cached_working_model not in DEPRECATED_TRANSFORM_MODELS
            and self._cached_working_model not in skip
        ):
            chain.append(self._cached_working_model)
        if (
            preferred
            and preferred.startswith(("gemini-", "gemma-"))
            and preferred not in DEPRECATED_TRANSFORM_MODELS
            and preferred not in skip
            and preferred not in chain
        ):
            chain.append(preferred)
        for m in DEFAULT_TRANSFORM_MODEL_CHAIN:
            if m not in chain and m not in skip:
                chain.append(m)
        if not chain:
            # Reset session caches if every static model was marked unavailable/exhausted
            self._unavailable_models.clear()
            self._daily_exhausted_models.clear()
            chain = list(DEFAULT_TRANSFORM_MODEL_CHAIN)
        return chain

    def _discover_live_models(self, api_key: str, exclude: set) -> List[str]:
        """Dynamically queries ListModels to find active generateContent-capable Gemini models."""
        try:
            resp = self.session.get(
                GEMINI_API_BASE,
                headers={"x-goog-api-key": api_key},
                timeout=(self.CONNECT_TIMEOUT, 6.0),
            )
            if not isinstance(getattr(resp, "status_code", None), int) or resp.status_code != 200:
                return []
            data = resp.json()
            candidates: List[str] = []
            blocked = exclude | self._unavailable_models | self._daily_exhausted_models
            for item in data.get("models", []):
                name = str(item.get("name", "")).replace("models/", "").strip()
                methods = item.get("supportedGenerationMethods", []) or []
                low = name.lower()
                if (
                    not name
                    or "generateContent" not in methods
                    or not low.startswith(("gemini-", "gemma-"))
                    or name in DEPRECATED_TRANSFORM_MODELS
                    or name in blocked
                    or any(skip in low for skip in ("-tts", "-image", "robotics", "computer-use", "transcribe", "nano-banana", "embedding", "aqa", "deep-research"))
                ):
                    continue
                candidates.append(name)
            # Prefer Gemini flash first, then Gemma 4, then other active models
            candidates.sort(key=lambda m: (0 if ("gemini-" in m.lower() and "flash" in m.lower()) else (1 if "gemma-4" in m.lower() else 2), m))
            return candidates[:6]
        except Exception as e:
            logger.debug(f"GeminiTransformService ListModels discovery note: {e}")
            return []

    @staticmethod
    def _clean_response_text(text: str, preserve_fences: bool = False) -> str:
        cleaned = (text or "").strip()
        if not cleaned:
            return ""
        if not preserve_fences and cleaned.startswith("```") and cleaned.endswith("```"):
            lines = cleaned.splitlines()
            if len(lines) >= 3:
                cleaned = "\n".join(lines[1:-1]).strip()
        # Strip accidental surrounding quotes if short single-block response
        if (
            not preserve_fences
            and len(cleaned) >= 2
            and "\n" not in cleaned
            and ((cleaned.startswith('"') and cleaned.endswith('"')) or (cleaned.startswith("'") and cleaned.endswith("'")))
        ):
            cleaned = cleaned[1:-1].strip()
        return cleaned

    @staticmethod
    def _extract_error_detail(response: requests.Response) -> str:
        try:
            data = response.json()
            msg = data.get("error", {}).get("message", "")
            if msg:
                return str(msg).strip()
        except Exception:
            pass
        return (response.text or f"HTTP {response.status_code}")[:240]

    def get_groq_api_key(self) -> str:
        """Resolves configured Groq API key."""
        if self.config_manager is not None:
            try:
                k = self.config_manager.get("groq_api_key") or os.environ.get("GROQ_API_KEY", "")
                if k:
                    return str(k).strip()
            except Exception:
                pass
        return str(os.environ.get("GROQ_API_KEY", "")).strip()

    def _invoke_groq(
        self,
        system_instruction: str,
        user_content: str,
        temperature: float = 0.1,
        max_tokens: int = 4096,
        preserve_fences: bool = False,
        start_time: float = 0.0,
    ) -> Optional[GeminiTransformResult]:
        """Executes ultra-low latency (< 0.25s) text transformation on Groq LPUs."""
        groq_key = self.get_groq_api_key()
        if not groq_key or groq_key in self._groq_invalid_keys:
            return None

        headers = {
            "Authorization": f"Bearer {groq_key}",
            "Content-Type": "application/json",
        }
        messages = []
        if system_instruction and system_instruction.strip():
            messages.append({"role": "system", "content": system_instruction.strip()})
        messages.append({"role": "user", "content": user_content.strip()})

        t_start = start_time or time.time()
        for model in GROQ_TRANSFORM_MODELS:
            payload = {
                "model": model,
                "messages": messages,
                "temperature": float(temperature),
                "max_tokens": min(int(max_tokens), 2048),
            }
            try:
                resp = self.session.post(
                    GROQ_API_CHAT,
                    json=payload,
                    headers=headers,
                    timeout=(self.CONNECT_TIMEOUT, self.READ_TIMEOUT),
                )
                if resp.status_code == 200:
                    data = resp.json()
                    choices = data.get("choices") or []
                    if choices:
                        raw_out = choices[0].get("message", {}).get("content", "").strip()
                        cleaned = self._clean_response_text(raw_out, preserve_fences=preserve_fences)
                        if cleaned:
                            self.last_model_used = f"groq-{model}"
                            self.last_error = ""
                            logger.info(f"Groq LPU semantic polish completed via {model} in {time.time() - t_start:.3f}s")
                            return GeminiTransformResult(
                                success=True,
                                text=cleaned,
                                model_used=f"groq-{model}",
                                latency_seconds=round(time.time() - t_start, 3),
                            )
                elif resp.status_code == 404:
                    continue
                elif resp.status_code in (401, 403):
                    self._groq_invalid_keys.add(groq_key)
                    logger.warning(f"Groq API returned HTTP {resp.status_code}. Caching key as unauthorized/invalid.")
                    break
            except Exception as e:
                logger.debug(f"Groq transform exception on {model}: {e}")
                continue
        return None

    def generate(
        self,
        system_instruction: str,
        user_content: str,
        temperature: float = 0.2,
        max_tokens: int = 4096,
        api_key_override: str = "",
        preserve_fences: bool = False,
    ) -> GeminiTransformResult:
        """
        Executes a Gemini generateContent call with resilient model fallback and instant fast-fail
        on missing or rejected API credentials.
        """
        start_time = time.time()
        payload_text = (user_content or "").strip()
        if not payload_text:
            return GeminiTransformResult(
                success=False,
                error_type="EMPTY_INPUT",
                error_message="No text was provided to transform.",
            )

        # Step 3: Fast Semantic Polish via Groq LPU (< 0.25s)
        # Prioritize ultra-low latency Groq LPU when configured
        groq_res = self._invoke_groq(
            system_instruction=system_instruction,
            user_content=payload_text,
            temperature=temperature,
            max_tokens=max_tokens,
            preserve_fences=preserve_fences,
            start_time=start_time,
        )
        if groq_res and groq_res.success and groq_res.text:
            return groq_res

        api_key = self.get_api_key(override_key=api_key_override)
        if not api_key:
            msg = "Gemini API key is not configured. Open Settings -> API & Models to enter your Gemini API key."
            self.last_error = msg
            return GeminiTransformResult(
                success=False,
                error_type="EMPTY_KEY",
                error_message=msg,
            )

        if api_key in self._gemini_invalid_keys:
            msg = "Gemini API key is invalid or unauthorized (cached fast-fail)."
            self.last_error = msg
            return GeminiTransformResult(
                success=False,
                error_type="INVALID_KEY",
                error_message=msg,
                latency_seconds=0.0,
            )

        base_body: Dict[str, Any] = {
            "contents": [{"role": "user", "parts": [{"text": payload_text}]}],
            "generationConfig": {
                "temperature": float(temperature),
                "maxOutputTokens": int(max_tokens),
            },
        }
        if system_instruction and system_instruction.strip():
            base_body["systemInstruction"] = {
                "parts": [{"text": system_instruction.strip()}]
            }

        headers = {
            "Content-Type": "application/json",
            "x-goog-api-key": api_key,
        }

        last_err_type = "UNKNOWN"
        last_err_code: Optional[int] = None
        last_err_msg = "Gemini transformation failed."
        transient_models: List[str] = []
        network_models: List[str] = []
        tried_models: set = set()
        retry_hint_sec: float = 0.0

        def _invoke_model(model_name: str) -> Optional[GeminiTransformResult]:
            nonlocal last_err_type, last_err_code, last_err_msg, retry_hint_sec
            tried_models.add(model_name)

            req_body = {
                "contents": base_body["contents"],
                "generationConfig": dict(base_body["generationConfig"]),
                "store": False,
            }
            if "systemInstruction" in base_body:
                req_body["systemInstruction"] = base_body["systemInstruction"]
            # Minimize thinking overhead for fast, deterministic sub-second transforms
            low_model = model_name.lower()
            if any(v in low_model for v in ("2.5", "3.0", "3.5", "3.7", "3.8")) and "pro" not in low_model:
                req_body["generationConfig"]["thinkingConfig"] = {"thinkingBudget": 0}
            elif "gemma-4" in low_model:
                req_body["generationConfig"]["thinkingConfig"] = {"thinkingLevel": "MINIMAL"}

            url = f"{GEMINI_API_BASE}/{model_name}:generateContent"
            for attempt_cfg in range(2):
                try:
                    # Adaptive fast-fail timeout: 2.0s connect, 6.0s read for sub-second user responsiveness
                    resp = self.session.post(
                        url,
                        json=req_body,
                        headers=headers,
                        timeout=(self.CONNECT_TIMEOUT, min(6.0, self.READ_TIMEOUT)),
                    )
                except requests.exceptions.Timeout:
                    last_err_type = "TIMEOUT"
                    last_err_msg = f"Gemini request timed out after {self.READ_TIMEOUT:.0f}s."
                    logger.warning(f"GeminiTransformService timeout on {model_name}")
                    return None
                except requests.exceptions.RequestException as e:
                    last_err_type = "NETWORK_ERROR"
                    last_err_msg = f"Network error contacting Gemini API: {e}"
                    logger.warning(f"GeminiTransformService network error on {model_name}: {e}")
                    if model_name not in network_models:
                        network_models.append(model_name)
                    return None

                if resp.status_code == 200:
                    try:
                        data = resp.json()
                        candidates = data.get("candidates") or []
                        if not candidates:
                            last_err_type = "EMPTY_RESPONSE"
                            last_err_msg = "Gemini returned no output candidates."
                            return None
                        parts = candidates[0].get("content", {}).get("parts", [])
                        non_thought = [p.get("text", "") for p in parts if isinstance(p, dict) and not p.get("thought")]
                        text_parts = non_thought if non_thought else [p.get("text", "") for p in parts if isinstance(p, dict)]
                        raw_out = "".join(text_parts).strip()
                        cleaned = self._clean_response_text(raw_out, preserve_fences=preserve_fences)
                        if not cleaned:
                            last_err_type = "EMPTY_RESPONSE"
                            last_err_msg = "Gemini returned an empty transformation."
                            return None
                        self._cached_working_model = model_name
                        self.last_model_used = model_name
                        self.last_error = ""
                        return GeminiTransformResult(
                            success=True,
                            text=cleaned,
                            model_used=model_name,
                            latency_seconds=round(time.time() - start_time, 3),
                        )
                    except Exception as parse_err:
                        last_err_type = "PARSE_ERROR"
                        last_err_msg = f"Malformed response from Gemini API: {parse_err}"
                        return None

                detail = self._extract_error_detail(resp)
                last_err_code = resp.status_code

                # Retry once without thinkingConfig if model rejects that field
                if (
                    resp.status_code == 400
                    and attempt_cfg == 0
                    and "thinkingConfig" in req_body["generationConfig"]
                    and "thinking" in detail.lower()
                ):
                    req_body["generationConfig"].pop("thinkingConfig", None)
                    continue

                # Instant fast-fail on authentication / bad key errors (HTTP 400 / 401 / 403)
                if resp.status_code in (401, 403) or (
                    resp.status_code == 400 and ("api key" in detail.lower() or "api_key" in detail.lower() or "key" in detail.lower())
                ):
                    self._gemini_invalid_keys.add(api_key)
                    msg = f"Invalid or unauthorized Gemini API key (HTTP {resp.status_code}): {detail}"
                    self.last_error = msg
                    return GeminiTransformResult(
                        success=False,
                        model_used=model_name,
                        error_code=resp.status_code,
                        error_type="INVALID_KEY",
                        error_message=msg,
                        latency_seconds=round(time.time() - start_time, 3),
                    )

                if resp.status_code == 429:
                    last_err_type = "RATE_LIMITED"
                    last_err_msg = f"Gemini API rate limit or quota reached (HTTP 429): {detail}"
                    logger.warning(f"GeminiTransformService 429 on {model_name}: {detail}")
                    if self._cached_working_model == model_name:
                        self._cached_working_model = ""
                    low_detail = detail.lower()
                    if "per day" in low_detail or "perday" in low_detail or re.search(r"retry in \d+h", low_detail):
                        self._daily_exhausted_models.add(model_name)
                    else:
                        m_sec = re.search(r"retry in (\d+(?:\.\d+)?)s", low_detail)
                        if m_sec:
                            hint = float(m_sec.group(1))
                            if retry_hint_sec == 0.0 or hint < retry_hint_sec:
                                retry_hint_sec = hint
                        if model_name not in transient_models:
                            transient_models.append(model_name)
                    return None

                if resp.status_code == 404:
                    last_err_type = "MODEL_NOT_FOUND"
                    last_err_msg = f"Gemini model {model_name} unavailable (HTTP 404): {detail}"
                    if self._cached_working_model == model_name:
                        self._cached_working_model = ""
                    self._unavailable_models.add(model_name)
                    logger.info(f"GeminiTransformService trying next fallback after 404 on {model_name}")
                    return None

                if resp.status_code >= 500:
                    last_err_type = "SERVER_ERROR"
                    last_err_msg = f"Gemini service error (HTTP {resp.status_code}): {detail}"
                    logger.warning(f"GeminiTransformService 5xx on {model_name}: {detail}")
                    if self._cached_working_model == model_name:
                        self._cached_working_model = ""
                    if model_name not in transient_models:
                        transient_models.append(model_name)
                    return None

                last_err_type = "API_ERROR"
                last_err_msg = f"Gemini API error (HTTP {resp.status_code}): {detail}"
                return GeminiTransformResult(
                    success=False,
                    model_used=model_name,
                    error_code=resp.status_code,
                    error_type=last_err_type,
                    error_message=last_err_msg,
                    latency_seconds=round(time.time() - start_time, 3),
                )
            return None

        # Pass 1: Configured + active verified fallback chain
        for model_name in self._get_model_chain():
            res = _invoke_model(model_name)
            if res is not None:
                return res

        # Pass 2: Dynamic ListModels discovery if all static candidates returned 404 or hit daily RPD exhaustion
        if last_err_type == "MODEL_NOT_FOUND" or (last_err_type == "RATE_LIMITED" and not transient_models):
            discovered = self._discover_live_models(api_key, exclude=tried_models)
            for disc_model in discovered:
                res = _invoke_model(disc_model)
                if res is not None:
                    return res

        # Pass 3: Exponential backoff for 429/5xx (respecting per-minute retry-in-Xs hints up to 65s)
        if transient_models:
            wait_schedule = [min(65.0, retry_hint_sec + 1.5)] if (0.0 < retry_hint_sec <= 65.0) else [0.6, 1.2]
            for backoff_sec in wait_schedule:
                time.sleep(backoff_sec)
                for retry_model in transient_models[:3]:
                    res = _invoke_model(retry_model)
                    if res is not None:
                        return res

        # Pass 4: Recover from brief DNS / socket blips without failing immediately
        if network_models and not transient_models:
            for net_backoff in (2.0, 5.0):
                time.sleep(net_backoff)
                res = _invoke_model(network_models[0])
                if res is not None:
                    return res

        self.last_error = last_err_msg
        return GeminiTransformResult(
            success=False,
            error_code=last_err_code,
            error_type=last_err_type,
            error_message=last_err_msg,
            latency_seconds=round(time.time() - start_time, 3),
        )

