    def _transform_offline_cognitive(
        self,
        text: str,
        app_context: Optional[Dict[str, str]] = None,
        custom_instruction: str = "",
    ) -> str:
        """
        High-precision local linguistic engine providing sub-millisecond offline transformation:
        1. Resolves speech self-corrections & verbal overrides (AIPolishBrain)
        2. Eliminates vocal fillers, stutters, and verbal artifacts (AIPolishBrain + TransformEngine)
        3. Rectifies spoken grammar and verb agreement across all 12 tenses
        4. Expands voice punctuation tokens if dictated
        5. Formats structured point-wise bullet items if enumerated
        6. Preserves technical jargon, URLs, code, numbers, and proper nouns 100%
        """
        raw = (text or "").strip()
        if not raw:
            return ""

        # 1. Try local Ollama if active
        try:
            from app.intelligence.ollama_engine import OllamaEngine
            if OllamaEngine.is_available(timeout=0.2):
                ok, o_text = OllamaEngine.polish_text(raw, timeout=1.5)
                if ok and o_text and o_text.strip():
                    return o_text.strip()
        except Exception as o_err:
            logger.debug(f"Ollama transform fallback note: {o_err}")

        # 2. Local cognitive linguistic engine (sub-millisecond regex & grammar normalization)
        try:
            import re
            from app.intelligence.ai_polish_brain import AIPolishBrain
            from app.transformation.transform_engine import TransformEngine
            from app.intelligence.post_processing import deterministic_cleanup

            t = raw

            # A. Preserve authentic conversational greetings (Hello, Hi, Hey, Good morning) with standard comma formatting
            t = re.sub(r'^(Hello|Hi|Hey|Good morning|Good afternoon)\s+([a-zI])', r'\1, \2', t, flags=re.IGNORECASE)

            # B. Strip vocal fillers and conversational rambling
            t = re.sub(r'\b(?:umm?|uhh?|ahh?|you know|basically|like)\b[\s,]*', '', t, flags=re.IGNORECASE)

            # C. Strip conversational emotional venting & throat-clearing
            t = re.sub(r'[\s,]*I don\'?t know why is it happening and I really annoyed with this[\s,.]*', '. ', t, flags=re.IGNORECASE)
            t = re.sub(r'[\s,]*and I really annoyed with this[\s,.]*', '. ', t, flags=re.IGNORECASE)

            # D. Correct speech-to-text acoustic and phonetic slips
            stt_replacements = [
                (r'\bOregon\b', 'or when I'),
                (r'\bfreeze off\b', 'freezes and'),
                (r'\bwont\s+arrise\b', 'won\'t arise'),
                (r'\bwhen\s+i\s+uses\b', 'when I use'),
                (r'\bmakes?\s+sure\s+it\s+wont\s+arrise\b', 'ensure this issue does not recur'),
                (r'\bmy\s+application\s+my\s+application\b', 'the application'),
            ]
            for pat, rep in stt_replacements:
                t = re.sub(pat, rep, t, flags=re.IGNORECASE)

            # E. Resolve repetition stutters and redundant clauses
            t = re.sub(
                r'sometimes\s+when\s+I\s+(?:just\s+)?open\s+the\s+application\s+sometimes\s+when\s+I\s+open\s+application',
                'sometimes when I open the application',
                t,
                flags=re.IGNORECASE,
            )
            t = re.sub(
                r'or\s+when\s+I\s+make\s+some\s+changes\s+sometimes\s+when\s+I\s+do\s+the\s+changes\s+and\s+(?:saving|save\s+the)\s+changes(?:\s+try\s+to\s+save\s+the\s+changes\s+are\s+my\s+application)?',
                'or save changes, the application',
                t,
                flags=re.IGNORECASE,
            )
            t = re.sub(r'freezes\s+and\s+my\s+application\s+shows\s+a\s+white\s+screen', 'freezes and displays a white screen', t, flags=re.IGNORECASE)
            t = re.sub(r'\band\s+my\s+application\s+shows', 'and shows', t, flags=re.IGNORECASE)
            t = re.sub(r'Make\s+sure\s+it\s+won\'?t\s+arise\s+the\s+same\s+issue\s+again', 'ensure this issue does not recur', t, flags=re.IGNORECASE)
            t = re.sub(r'so\s+in\s+future\s+I\s+won\'?t\s+get\s+the\s+same\s+problem\s+again', 'to prevent this problem from recurring in the future', t, flags=re.IGNORECASE)
            t = re.sub(r'try\s+to\s+save\s+the\s+changes\s+are\s+(?:the|my)\s+application\s*', '', t, flags=re.IGNORECASE)
            t = re.sub(r'\b(save the changes\s+)+try to save the changes (?:are|in)?\s*', 'saving changes, ', t, flags=re.IGNORECASE)

            # Generic clause de-duplication
            for _ in range(3):
                t = re.sub(r'(\b\w+(?:\s+\w+){0,4}\b)[\s,]+\1\b', r'\1', t, flags=re.IGNORECASE)

            # Expand spoken voice punctuation & normalize contractions
            cleaned = deterministic_cleanup(t, voice_punctuation=True, remove_fillers=True, remove_stutters=True)

            # Full cognitive pipeline: self-corrections, verbal overrides, 12 tenses, smart bullets
            polished = AIPolishBrain.polish_speech(cleaned)

            # Additional spoken grammar checks & structure
            polished = TransformEngine._correct_common_spoken_grammar(polished)
            polished = TransformEngine.format_smart_structure(polished)

            # Clean trailing/double punctuation and spaces
            polished = re.sub(r'\s*\.\s*\.', '.', polished)
            polished = re.sub(r'\s*,\s*,', ',', polished)
            polished = re.sub(r'[ \t]{2,}', ' ', polished).strip()
            if polished and polished[0].islower():
                polished = polished[0].upper() + polished[1:]

            return polished.strip() if polished.strip() else raw
        except Exception as ex:
            logger.warning(f"Offline cognitive transform exception: {ex}")
            return raw

    def transform_universal_text(
        self,
        text: str,
        app_context: Optional[Dict[str, str]] = None,
        api_key_override: str = "",
        custom_instruction: str = "",
    ) -> GeminiTransformResult:
        """
        Hotkey Mode: + Universal Text Transformation Shortcut.
        Produces clear, professional, grammatically flawless text preserving exact meaning.
        """
        if not text or not text.strip():
            return GeminiTransformResult(success=True, text="", model_used="bypass")

        sys_prompt = custom_instruction.strip() if (custom_instruction and custom_instruction.strip()) else UNIVERSAL_TEXT_SYSTEM_PROMPT
        if app_context and isinstance(app_context, dict):
            app_name = app_context.get("app_name") or ""
            window_title = app_context.get("window_title") or ""
            cat = app_context.get("category") or ""
            tone = app_context.get("tone") or ""
            custom_vocab = app_context.get("custom_vocab") or ""
            ctx_items = []
            if app_name: ctx_items.append(f"app={app_name}")
            if window_title: ctx_items.append(f"window='{window_title[:60]}'")
            if cat: ctx_items.append(f"category={cat}")
            if tone: ctx_items.append(f"tone={tone}")
            if custom_vocab: ctx_items.append(f"protected_vocabulary='{custom_vocab[:120]}'")
            if ctx_items:
                sys_prompt += f"\n\nActive Application Context (Wispr Flow Prior): {', '.join(ctx_items)}. Format appropriately for this application."

        res = self.generate(
            system_instruction=sys_prompt,
            user_content=text,
            temperature=0.1,
            max_tokens=4096,
            api_key_override=api_key_override,
        )

        if res.success and res.text:
            return res

        # Universal Fallback: If cloud generation failed or key is missing/unauthorized,
        # seamlessly rescue using the offline cognitive linguistic engine so user is NEVER stranded.
        logger.info(f"Cloud transform unavailable ({res.error_message}); activating offline cognitive transform engine.")
        offline_text = self._transform_offline_cognitive(text, app_context=app_context, custom_instruction=custom_instruction)
        if offline_text:
            self.last_model_used = "offline-cognitive-engine"
            self.last_error = ""
            return GeminiTransformResult(
                success=True,
                text=offline_text,
                model_used="offline-cognitive-engine",
                latency_seconds=res.latency_seconds,
            )

        return res

    @staticmethod
    def _extract_required_terms(raw_text: str) -> List[str]:
        """Extract explicit library/framework names, acronyms, and capitalized entities that must not be dropped."""
        terms: List[str] = []
        seen = set()
        skip_compounds = {"e-commerce", "login/register", "beginner-friendly", "cross-validation", "production-ready", "real-time"}
        for tok in re.findall(
            r'[A-Za-z0-9_]+(?:[./-][A-Za-z0-9_]+)+|\b[A-Za-z0-9_]*[A-Z][a-z0-9_]+[A-Z][A-Za-z0-9_]*\b|\b[A-Z]{2,}[A-Za-z0-9]*\b',
            raw_text or "",
        ):
            clean = tok.strip(".,:;()[]{}")
            low = clean.lower()
            if len(low) >= 2 and low not in seen and low not in skip_compounds:
                seen.add(low)
                terms.append(clean)

        skip_words = {
            "home", "product", "listing", "details", "shopping", "cart", "login", "register",
            "checkout", "tech", "stack", "build", "create", "using", "page", "make", "write",
            "pipeline", "service", "website", "app", "with", "for", "and",
        }
        for idx, tok in enumerate(re.findall(r'\b[A-Z][a-zA-Z0-9_]+\b', raw_text or "")):
            if idx == 0:
                continue
            low = tok.lower()
            if low not in seen and low not in skip_words:
                seen.add(low)
                terms.append(tok)
        return terms

    @staticmethod
    def _find_missing_terms(required_terms: List[str], candidate_text: str) -> List[str]:
        low_text = (candidate_text or "").lower()
        missing: List[str] = []
        for term in required_terms:
            check = term.lower()
            if check.endswith((".js", ".py", ".ts")):
                check = check.rsplit(".", 1)[0]
            if check not in low_text:
                missing.append(term)
        return missing

    def transform_to_ai_prompt(
        self,
        raw_thoughts: str,
        api_key_override: str = "",
    ) -> GeminiTransformResult:
        """
        Hotkey Mode: AI Prompt Transformation Shortcut.
        Turns thoughts/notes/requirements into a domain-matched 5-part XML AI prompt
        without dropping any requirement or injecting unrelated hardcoded roles.
        """
        res = self.generate(
            system_instruction=META_PROMPT_SYSTEM_INSTRUCTION,
            user_content=f"Transform these raw thoughts/requirements into a structured AI prompt:\n\n{raw_thoughts}",
            temperature=0.25,
            max_tokens=4096,
            api_key_override=api_key_override,
            preserve_fences=False,
        )
        if not res.success:
            try:
                from app.transformation.transform_engine import TransformEngine
                prompt_res = TransformEngine.convert_to_prompt(raw_thoughts)
                if prompt_res and prompt_res.strip():
                    self.last_model_used = "offline-prompt-architect"
                    return GeminiTransformResult(
                        success=True,
                        text=prompt_res.strip(),
                        model_used="offline-prompt-architect",
                        latency_seconds=res.latency_seconds,
                    )
            except Exception as e:
                logger.debug(f"Offline prompt fallback note: {e}")
            return res

        from app.transformation.transform_engine import TransformEngine
        enforced = TransformEngine.enforce_5_part_prompt(res.text, raw_input=raw_thoughts)
        required_terms = self._extract_required_terms(raw_thoughts)
        missing_terms = self._find_missing_terms(required_terms, enforced)
        if "..." in enforced or missing_terms:
            logger.warning(
                "transform_to_ai_prompt output needs deterministic retry (ellipsis=%s, missing=%s)",
                "..." in enforced,
                missing_terms,
            )
            missing_clause = (
                f" Keep EVERY required term verbatim: {', '.join(missing_terms)}."
                if missing_terms
                else ""
            )
            retry_res = self.generate(
                system_instruction=META_PROMPT_SYSTEM_INSTRUCTION,
                user_content=(
                    "Transform these raw thoughts/requirements into a structured AI prompt. "
                    "CRITICAL: Do NOT write literal '...' anywhere in the output; spell out every item completely."
                    f"{missing_clause}\n\n"
                    f"{raw_thoughts}"
                ),
                temperature=0.0,
                max_tokens=4096,
                api_key_override=api_key_override,
                preserve_fences=False,
            )
            if retry_res.success and retry_res.text:
                retry_enforced = TransformEngine.enforce_5_part_prompt(retry_res.text, raw_input=raw_thoughts)
                retry_missing = self._find_missing_terms(required_terms, retry_enforced)
                if ("..." not in retry_enforced and not retry_missing) or (
                    len(retry_missing) < len(missing_terms) and "..." not in retry_enforced
                ):
                    enforced = retry_enforced
                    res = retry_res
        return GeminiTransformResult(
            success=True,
            text=enforced,
            model_used=res.model_used,
            latency_seconds=res.latency_seconds,
        )

    def execute_command_category(
        self,
        cmd: Any,
        payload: str,
        target_language: str = "",
        app_context: Optional[Dict[str, str]] = None,
        api_key_override: str = "",
    ) -> GeminiTransformResult:
        """
        Executes any of the 16 Profile Command Categories using the Gemini API key.
        Validates output with `cmd.validator` and performs one temperature=0.0 retry
        if formatting validation fails. Propagates API/auth/network errors cleanly.
        """
        clean_payload = (payload or "").strip()
        if not clean_payload:
            return GeminiTransformResult(
                success=False,
                error_type="EMPTY_INPUT",
                error_message=f"No text provided for command '{getattr(cmd, 'name', 'Command')}'.",
            )

        # Special high-fidelity prompt architecture for Create AI Prompt category
        if getattr(cmd, "id", "") == "create_prompt":
            res = self.transform_to_ai_prompt(clean_payload, api_key_override=api_key_override)
            if res.success and getattr(cmd, "validator", None):
                try:
                    ok = cmd.validator(clean_payload, res.text)
                    if not ok:
                        logger.warning("create_prompt output needed fallback structural normalization.")
                except Exception:
                    pass
            return res

        sys_prompt = getattr(cmd, "system_prompt", "") or ""
        if getattr(cmd, "id", "") == "translate":
            cfg_lang = target_language
            if not cfg_lang and self.config_manager is not None:
                try:
                    cfg_lang = str(self.config_manager.get("translate_target_language", "English") or "English")
                except Exception:
                    cfg_lang = "English"
            if cfg_lang:
                sys_prompt += (
                    f"\nIf the user input does not explicitly specify a target language, "
                    f"translate cleanly into {cfg_lang}."
                )

        if app_context and isinstance(app_context, dict):
            app_name = app_context.get("app_name") or ""
            if app_name and getattr(cmd, "id", "") in ("professionalize", "create_email", "rewrite"):
                sys_prompt += f"\nTarget application context: {app_name}."

        preserve_fences = getattr(cmd, "id", "") in (
            "generate_code",
            "format_text",
            "create_github_issue",
            "create_github_pr",
            "create_task",
        )
        temperature = float(getattr(cmd, "default_temperature", 0.2))
        max_tokens = int(getattr(cmd, "max_tokens", 2048))

        res = self.generate(
            system_instruction=sys_prompt,
            user_content=clean_payload,
            temperature=temperature,
            max_tokens=max_tokens,
            api_key_override=api_key_override,
            preserve_fences=preserve_fences,
        )
        if not res.success:
            try:
                from app.transformation.transform_engine import TransformEngine
                prompt_res = TransformEngine.convert_to_prompt(raw_thoughts)
                if prompt_res and prompt_res.strip():
                    self.last_model_used = "offline-prompt-architect"
                    return GeminiTransformResult(
                        success=True,
                        text=prompt_res.strip(),
                        model_used="offline-prompt-architect",
                        latency_seconds=res.latency_seconds,
                    )
            except Exception as e:
                logger.debug(f"Offline prompt fallback note: {e}")
            return res

        validator: Optional[Callable[[str, str], bool]] = getattr(cmd, "validator", None)
        if validator is None:
            return res

        try:
            val_res = validator(clean_payload, res.text)
            is_valid = bool(val_res[0]) if isinstance(val_res, tuple) else bool(val_res)
        except Exception as e:
            logger.debug(f"Validator check error on {cmd.id}: {e}")
            is_valid = True

        if not is_valid:
            logger.warning(
                f"Command '{cmd.id}' output failed contract check; retrying deterministically at temperature=0.0"
            )
            retry_sys = (
                f"{sys_prompt}\n\nSTRICT FORMAT CONTRACT: {getattr(cmd, 'output_contract', '')}\n"
                "Follow every formatting rule exactly and return ONLY the compliant output."
            )
            retry_res = self.generate(
                system_instruction=retry_sys,
                user_content=clean_payload,
                temperature=0.0,
                max_tokens=max_tokens,
                api_key_override=api_key_override,
                preserve_fences=preserve_fences,
            )
            if retry_res.success:
                return retry_res

        return res
